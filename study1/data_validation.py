def _is_url(s: str) -> bool:
    s = s.strip().lower()
    return s.startswith("http://") or s.startswith("https://")


def load_dataset_mat_only(
    source: str,
    expected_N: int,
    expected_L: int,
    debug: bool = False,
    fallback_name: str = "UUV_tmp.mat",
) -> np.ndarray:

    src = source.strip()

    # URL
    if _is_url(src):
        try:
            b = fetch_gdrive_mat_bytes(src)
            return load_uuv_mat_from_bytes(b, expected_N=expected_N, expected_L=expected_L, debug=debug)
        except Exception as e:
            if debug:
                print("\n[DEBUG] In-memory fetch failed, falling back to gdown.\nReason:", repr(e))
            p = gdown_download(src, Path(fallback_name))
            b = Path(p).read_bytes()
            return load_uuv_mat_from_bytes(b, expected_N=expected_N, expected_L=expected_L, debug=debug)

    # Local path
    p = Path(src)
    if not p.exists():
        raise FileNotFoundError(f"File not found: {p}")
    b = p.read_bytes()
    return load_uuv_mat_from_bytes(b, expected_N=expected_N, expected_L=expected_L, debug=debug)


def build_hfm_echo_template(
    fs: float = 5000.0,
    tr: float = 0.01,
    alpha: float = 20.0,
    T: float = 0.1646,
    tau: float = 0.04,
    A: float = 0.95,
    Td: float = 0.2046,
) -> Tuple[np.ndarray, Dict[str, Any]]:
    Ts = 1.0 / fs
    M = int(round(T / Ts)) + 1
    N = int(round(Td / Ts)) + 1
    n0 = int(round(tau / Ts))

    n = np.arange(M)
    t = tr + n * Ts
    s = np.cos(2.0 * math.pi * alpha * np.log(t / tr))

    x = np.zeros(N, dtype=float)
    start = n0
    end = n0 + M
    if end > N:
        raise ValueError(f"Echo (n0+M={end}) exceeds N={N}.")
    x[start:end] = A * s

    meta = {
        "fs": fs, "Ts": Ts, "T": T, "Td": Td,
        "M": M, "N": N, "tau": tau, "n0": n0,
        "A": A, "tr": tr, "alpha": alpha,
        "support_start": start, "support_end": end - 1,
    }
    return x, meta


def check_set_relationship(
    R1: np.ndarray,
    R2: np.ndarray,
    x: np.ndarray,
    sigma2: float = 30.0,
    out_dir: Path = Path("outputs_check"),
    prefix: str = "Set2_minus_Set1",
    no_plots: bool = False,
) -> Dict[str, Any]:
    out_dir.mkdir(parents=True, exist_ok=True)

    if R1.shape != R2.shape:
        raise ValueError(f"R1 shape {R1.shape} != R2 shape {R2.shape}")
    N, L = R1.shape
    if x.shape != (N,):
        raise ValueError(f"x shape {x.shape} != (N,) where N={N}")

    D = R2 - R1  # (N, L)

    eps = 1e-12
    n0 = int(np.argmax(np.abs(x) > eps))  # first nonzero x index
    identical_prefix = bool(np.allclose(R1[:n0, :], R2[:n0, :], atol=1e-12, rtol=0)) if n0 > 0 else False

    row_std = D.std(axis=1)
    row_mean = D.mean(axis=1)

    a = float((row_mean @ x) / (x @ x))
    rmse = float(np.sqrt(np.mean((row_mean - a * x) ** 2)))
    corr = float(np.corrcoef(row_mean, x)[0, 1])


    mu1 = float(R1.mean())
    var1 = float(R1.var(ddof=1))


    Es = float(x @ x)
    ENR_lin = float(Es / sigma2)
    ENR_db = float(10.0 * np.log10(ENR_lin))

    results = {
        "N": int(N),
        "L": int(L),
        "n0_first_nonzero_of_x": int(n0),
        "identical_prefix_before_n0": identical_prefix,
        "max_row_std_before_n0": float(row_std[:n0].max()) if n0 > 0 else float(row_std.max()),
        "max_row_std_after_n0": float(row_std[n0:].max()),
        "scale_factor_a": a,
        "rmse": rmse,
        "correlation": corr,
        "set1_mean": mu1,
        "set1_var": var1,
        "Es": Es,
        "ENR_lin": ENR_lin,
        "ENR_db": ENR_db,
    }

    print("\n=== Relationship Test: does Set2 ≈ Set1 + x ? ===")
    print(f"Shapes: R1={R1.shape}, R2={R2.shape}, x={x.shape}")
    print(f"n0 (first nonzero x index): {n0}")
    print(f"R1 and R2 identical for rows [0..{n0-1}]?  {identical_prefix}")
    print("Std of D across hydrophones (should be ~0):")
    print(f"  max std before n0: {results['max_row_std_before_n0']:.3e}")
    print(f"  max std after  n0: {results['max_row_std_after_n0']:.3e}")
    print("\nFit mean(D over hydrophones) ≈ a*x:")
    print(f"  a (scale): {a:.9f}")
    print(f"  RMSE:     {rmse:.3e}")
    print(f"  Corr:     {corr:.12f}")
    print("\nNoise estimate from Set1:")
    print(f"  mean ~ {mu1:.4f}")
    print(f"  var  ~ {var1:.4f} (expected around sigma^2={sigma2})")
    print("\nTemplate ENR from energy Es/sigma^2:")
    print(f"  ENR = {ENR_lin:.6f}  ->  {ENR_db:.4f} dB")

    if not no_plots:

        plt.figure(figsize=(10, 4))
        plt.plot(x, label="Template x[n]")
        plt.plot(row_mean, "--", label="mean over hydrophones of (Set2-Set1)")
        plt.axvline(n0, linestyle=":", label=f"n0={n0}")
        plt.title("Check: Set2 - Set1 matches the echo template x[n]")
        plt.xlabel("Sample index n")
        plt.ylabel("Amplitude")
        plt.legend()
        plt.tight_layout()
        p1 = out_dir / f"{prefix}_overlay_x_vs_meanD.png"
        plt.savefig(p1, dpi=200)
        plt.show()


        plt.figure(figsize=(10, 4))
        plt.plot(row_std)
        plt.axvline(n0, linestyle=":")
        plt.title("Std across hydrophones of D = Set2 - Set1")
        plt.xlabel("Sample index n")
        plt.ylabel("Std across hydrophones")
        plt.tight_layout()
        p2 = out_dir / f"{prefix}_rowStd.png"
        plt.savefig(p2, dpi=200)
        plt.show()

        results["plot_overlay"] = str(p1)
        results["plot_rowStd"] = str(p2)

        print(f"\nSaved plots to: {out_dir.resolve()}")

    return results


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--set1", type=str, default=SET1_URL, help="Set1 URL/path to .mat")
    parser.add_argument("--set2", type=str, default=SET2_URL, help="Set2 URL/path to .mat")
    parser.add_argument("--sigma2", type=float, default=30.0)
    parser.add_argument("--out_dir", type=str, default="outputs_check")
    parser.add_argument("--debug_mat", action="store_true")
    parser.add_argument("--no_plots", action="store_true")


    args, _unknown = parser.parse_known_args(argv)

    x, meta = build_hfm_echo_template(fs=5000.0)
    expected_N = meta["N"]
    expected_L = 200

    print("Template meta:", meta)
    print(f"Loading datasets with expected shape ({expected_N},{expected_L}) ...")

    R1 = load_dataset_mat_only(args.set1, expected_N, expected_L, debug=args.debug_mat, fallback_name="UUV_Set1.mat")
    R2 = load_dataset_mat_only(args.set2, expected_N, expected_L, debug=args.debug_mat, fallback_name="UUV_Set2.mat")

    check_set_relationship(
        R1, R2, x,
        sigma2=args.sigma2,
        out_dir=Path(args.out_dir),
        prefix="Set2_minus_Set1",
        no_plots=args.no_plots,
    )

    return 0


