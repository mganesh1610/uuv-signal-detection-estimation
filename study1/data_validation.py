def _ensure_loader_module():
    loader_path = Path(__file__).resolve().parents[1] / LOADER_LOCAL_NAME
    if not loader_path.is_file():
        raise FileNotFoundError(f"Bundled loader not found: {LOADER_LOCAL_NAME}")
